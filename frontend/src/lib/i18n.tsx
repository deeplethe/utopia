const dictionaries: Record<Locale, Record<MessageKey, string>> = { en, "zh-CN": zh }
const STORAGE_KEY = "ontopilot.locale"

function initialLocale(): Locale {
  const saved = localStorage.getItem(STORAGE_KEY)
  if (saved === "en" || saved === "zh-CN") return saved
  return navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en"
}

function interpolate(message: string, values?: Record<string, string | number>) {
  if (!values) return message
  return message.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`))
}

interface I18nValue {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: Translate
}

const I18nContext = createContext<I18nValue | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(initialLocale)

  useEffect(() => {
    document.documentElement.lang = locale
    localStorage.setItem(STORAGE_KEY, locale)
  }, [locale])

  const value = useMemo<I18nValue>(() => ({
    locale,
    setLocale: setLocaleState,
    t: (key, values) => interpolate(dictionaries[locale][key] ?? en[key], values),
  }), [locale])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const value = useContext(I18nContext)
  if (!value) throw new Error("useI18n must be used inside I18nProvider")
  return value
}
