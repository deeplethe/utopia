-- 一个类别词的判定记下它当时看到的输入（0053 的类别词那一半，#795）。
--
-- 过期从前按时间戳判：绑到的类在判定之后改过，或判成 none / undecided 之后库里有类新建或
-- 修改。判定写在模型答完之后（`decided_at = now()`），模型答题期间改了类的定义，时间戳说
-- 判定更新，可两票看到的都是旧定义——这次改动从此不会再被问到（#795 复现过）。父边的增删
-- 不碰 `updated_at`，时间戳同样看不见。
--
-- `basis` 是给模型看的候选类的指纹：每个候选的 id、`updated_at` 与祖先闭包，在调模型之前
-- 从同一个快照里读。写判定时在同一事务里按当前的类重算，对不上就不收这份回复；worker 每轮
-- 按当前的输入重算，对不上就是过期。NULL = 这一列出现之前的代理判定，各重判一次；人的
-- 判定不带指纹，也不按指纹重判。
ALTER TABLE type_bindings ADD COLUMN basis TEXT;
