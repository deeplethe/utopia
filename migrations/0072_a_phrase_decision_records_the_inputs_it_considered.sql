-- 一条短语判定记下它当时看到的输入（0053，#807，#795）。
--
-- 过期从前按时间戳判：绑到的属性在判定之后改过，或判成 none 之后有属性新建。时间戳看不见
-- 两件事：类的父边（属性的定义域声明在祖先上，子类经继承命中——加一条父边能让一个判成
-- 「没有候选」的签名有了候选，去一条能让绑上的失去支撑），以及模型请求途中的编辑（判定
-- 写入晚于编辑，时间戳说它是新的，可两票看到的都是旧定义）。
--
-- `basis` 是判定时输入的指纹：两端类的祖先闭包、按继承命中的候选属性集合与各自的
-- `updated_at`。worker 每轮对每条活着的签名重算指纹，不一致就是过期——比的是**现在的**
-- 输入而不是时刻。NULL = 这一列出现之前的判定，各重判一次。
ALTER TABLE phrase_bindings ADD COLUMN basis TEXT;
