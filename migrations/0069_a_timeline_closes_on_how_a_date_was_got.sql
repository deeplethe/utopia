-- 时间线按解析等级收口（0045 第 3 刀）。
--
-- 引擎至今用一个数字决定后任能不能改写前任的历史：`facts.confidence` 低于 0.75 就不许它
-- 关上前一行，改记一条待审的矛盾。那个数字是个代理——它说的是抽取有多确信这条关系，
-- 不是这条关系的日期是怎么来的。0045 第 1、2 刀已经把后者算了出来，写在
-- `time_mentions.grade` 上：A 是文档写明的日期，B 是从文档自己的锚点算出来的，C 是锚不到。
-- 至今没有人读它。
--
-- 这一刀把等级带到行上，让引擎读它：起点是 A 或 B 的后任照常关上前任，起点是 C 的不许
-- 改写历史（它的位置本来就是猜的），跳过它、这一对交给人。数字从引擎里出去，仍留在
-- 列上给排序和显示用。
--
--   facts.valid_from_grade  这一行的起点是怎么来的。NULL = 没经过时间解析：人写的日期、
--                           规则算的、以及这张表在这一刀之前的每一行。**NULL 按 A 算**：
--                           日期是直接给的，不是从别处猜的，引擎照旧让它关上前任
--
-- 纯增量，不回填。
ALTER TABLE facts ADD COLUMN valid_from_grade TEXT
    CHECK (valid_from_grade IN ('A', 'B', 'C'));

COMMENT ON COLUMN facts.valid_from_grade IS
    '起点是怎么来的：A 写明、B 按锚点算出、C 锚不到；NULL 是没经过时间解析，按 A 算';
